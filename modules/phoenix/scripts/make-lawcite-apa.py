#!/usr/bin/env python3
"""Derive styles/lawcite-apa.csl from Zotero's stock apa.csl (APA 7th edition, with Bluebook legal references).

  python3 scripts/make-lawcite-apa.py /path/to/apa.csl      (writes styles/lawcite-apa.csl)

apa.csl is by Brenton M. Wiernik and Andrew Dunning, CC BY-SA 3.0; the derivative keeps that license and credit.
Three changes, all in the legal-reference macros, each asserted against the source so a changed upstream fails loudly:

  1. Congressional bills and hearings print the congress as "117th Cong." from the Session field (Zotero maps it to
     `chapter-number`) instead of "<legislative body> 117". The stock style expects the user to type "117th Cong." into
     the Legislative Body field; with the body entered normally ("House of Representatives") it printed it.
  2. A statute with a Section prints the code citation, "42 U.S.C. § 12101", even when it also has a public law number.
     The stock style dropped the section and printed "Pub. L. Nos. 101-336, 42 U.S.C." (the section missing).
  3. A public law number is always singular, "Pub. L. No. 101-336": public law numbers contain a hyphen, which the
     stock number label read as a range ("Nos.").
"""
import re, sys, datetime

src_path = sys.argv[1] if len(sys.argv) > 1 else None
if not src_path:
    sys.exit(__doc__)
s = open(src_path, encoding='utf-8').read()

def swap(old, new, label):
    global s
    if s.count(old) != 1:
        sys.exit(f'FAILED: {label}: expected one occurrence in the source, found {s.count(old)}')
    s = s.replace(old, new)

# ---- header
swap('<!-- This file was generated by the Style Variant Builder <https://github.com/citation-style-language/style-variant-builder>. To contribute changes, modify the template and regenerate variants. -->',
     '<!-- Derived from Zotero\'s apa.csl (APA 7th edition) by modules/phoenix/scripts/make-lawcite-apa.py: three corrections to legal references (bills and hearings, statutes). Everything else is unchanged. -->',
     'generated-file comment')
swap('<title>APA Style 7th edition</title>', '<title>Lawcite APA Style 7th edition</title>', 'title')
swap('<id>http://www.zotero.org/styles/apa</id>', '<id>http://www.zotero.org/styles/lawcite-apa</id>', 'id')
swap('<link href="http://www.zotero.org/styles/apa" rel="self"/>', '<link href="http://www.zotero.org/styles/lawcite-apa" rel="self"/>', 'self link')
swap('<link href="http://www.zotero.org/styles/apa-6th-edition" rel="template"/>', '<link href="http://www.zotero.org/styles/apa" rel="template"/>', 'template link')
swap('''    <category citation-format="author-date"/>''', '''    <contributor>
      <name>Jeremy Sheff</name>
    </contributor>
    <category citation-format="author-date"/>''', 'contributor')
swap('<summary>Author-date system of the Publication Manual of the American Psychological Association (2020)</summary>',
     '<summary>Author-date system of the Publication Manual of the American Psychological Association (2020), with corrected legal references for bills, hearings and statutes</summary>', 'summary')
s, n = re.subn(r'<updated>[^<]*</updated>', '<updated>%s</updated>' % datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%S+00:00'), s, count=1)
assert n == 1

# ---- 1. bills and hearings: "117th Cong."
swap('''  <macro name="legal-source-bill">
    <group delimiter=", ">
      <text macro="legal-identifier-bill-report"/>
      <group delimiter=" ">
        <text variable="authority"/>
        <!-- `chapter-number` is a session number -->
        <text variable="chapter-number"/>
      </group>''', '''  <!-- lawcite: a numeric session (Zotero's Session field, `chapter-number`) is the congress: "117th Cong." -->
  <macro name="legal-congress">
    <choose>
      <if is-numeric="chapter-number">
        <group delimiter=" ">
          <number form="ordinal" variable="chapter-number"/>
          <text value="Cong."/>
        </group>
      </if>
      <else>
        <group delimiter=" ">
          <text variable="authority"/>
          <text variable="chapter-number"/>
        </group>
      </else>
    </choose>
  </macro>
  <macro name="legal-source-bill">
    <group delimiter=", ">
      <text macro="legal-identifier-bill-report"/>
      <text macro="legal-congress"/>''', 'bill source')
swap('''  <macro name="legal-source-hearing">
    <group delimiter=" ">
      <text variable="authority"/>
      <!-- `chapter-number` is a session number -->
      <text variable="chapter-number"/>
    </group>
  </macro>''', '''  <macro name="legal-source-hearing">
    <text macro="legal-congress"/>
  </macro>''', 'hearing source')

# ---- 2 + 3. statutes
swap('''  <macro name="legal-source-legislation">
    <choose>
      <if variable="number">
        <!-- `number` is a public law number -->
        <group delimiter=", ">
          <group delimiter=" ">
            <choose>
              <if variable="genre">
                <text text-case="capitalize-first" variable="genre"/>
              </if>
              <else>
                <text form="short" term="legislation" text-case="capitalize-first"/>
              </else>
            </choose>
            <text macro="label-number-capitalized"/>
          </group>''', '''  <macro name="legal-source-legislation">
    <choose>
      <if variable="section">
        <!-- lawcite: a codified statute is cited to the code, "42 U.S.C. § 12101", even if it also has a public law number -->
        <group delimiter=" ">
          <text variable="volume"/>
          <text variable="container-title"/>
          <text macro="label-section-symbol"/>
        </group>
      </if>
      <else-if variable="number">
        <!-- `number` is a public law number; always singular ("No."), as these numbers contain a hyphen -->
        <group delimiter=", ">
          <group delimiter=" ">
            <choose>
              <if variable="genre">
                <text text-case="capitalize-first" variable="genre"/>
              </if>
              <else>
                <text form="short" term="legislation" text-case="capitalize-first"/>
              </else>
            </choose>
            <group delimiter=" ">
              <text term="number" form="short" text-case="capitalize-first"/>
              <text variable="number"/>
            </group>
          </group>''', 'statute head')
swap('''            <text variable="page-first"/>
          </group>
        </group>
      </if>
      <else>
        <group delimiter=" ">
          <text variable="volume"/>
          <text variable="container-title"/>
          <choose>
            <if variable="section">
              <text macro="label-section-symbol"/>
            </if>
            <else>
              <text variable="page-first"/>
            </else>
          </choose>
        </group>
      </else>
    </choose>
  </macro>
  <macro name="legal-source-regulation">''', '''            <text variable="page-first"/>
          </group>
        </group>
      </else-if>
      <else>
        <group delimiter=" ">
          <text variable="volume"/>
          <text variable="container-title"/>
          <text variable="page-first"/>
        </group>
      </else>
    </choose>
  </macro>
  <macro name="legal-source-regulation">''', 'statute tail')

out = 'styles/lawcite-apa.csl'
open(out, 'w', encoding='utf-8', newline='').write(s)
print('wrote', out, len(s), 'bytes')
